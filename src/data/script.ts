/**
 * What a grapheme card SPEAKS. TTS cannot say an isolated sound ("æ", "θ"),
 * and the letter's name would teach the wrong thing (the whole point of the
 * course is that `a` is not "เอ" in cat). The example word carries the sound,
 * so that is what the card plays.
 */
export function letterSound(c: ScriptChar): string {
  return c.word
}
